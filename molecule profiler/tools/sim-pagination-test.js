'use strict';
const assert = require('node:assert/strict');
const {paginateRanked} = require('../js/sim-pagination.js');
const list = Array.from({length:2258}, (_,i)=>({rank:i+1}));
const full = paginateRanked(list,0,1,50);
assert.equal(full.total,2258);
assert.equal(full.pageSize,50);
assert.equal(full.rows.length,50);
assert.equal(full.pages,46);
assert.equal(full.rows[0].rank,1);
const middle = paginateRanked(list,0,13,50);
assert.equal(middle.rows[0].rank,601);
assert.equal(middle.from,601);
assert.equal(middle.to,650);
assert.equal(middle.rows[middle.rows.length-1].rank,650);
const last = paginateRanked(list,0,9999,50);
assert.equal(last.page,46);
assert.equal(last.rows.length,8);
assert.equal(last.to,2258);
const top10 = paginateRanked(list,10,13);
assert.equal(top10.page,1);
assert.equal(top10.rows.length,10);
assert.equal(top10.total,10);
const top20 = paginateRanked(list,20,1);
assert.equal(top20.total,20);
assert.equal(top20.rows.length,20);
assert.deepEqual(paginateRanked([],0,1).rows,[]);
assert.equal(paginateRanked([],0,1).from,0);
assert.equal(paginateRanked(list,0,NaN).page,1);
assert.equal(paginateRanked(list,0,-1).page,1);
console.log('Similarity pagination regression tests passed');
