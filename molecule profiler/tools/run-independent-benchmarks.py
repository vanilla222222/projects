#!/usr/bin/env python3
"""Fetch pinned measurement datasets, verify bytes, evaluate frozen browser code."""
import argparse,csv,hashlib,io,json,subprocess,urllib.request
from datetime import datetime,timezone
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def run(cache,write=False):
 manifest=json.loads((ROOT/'validation/benchmark-sources.json').read_text());reports=[];cache.mkdir(parents=True,exist_ok=True)
 for dataset in manifest['datasets']:
  path=cache/(dataset['id']+'.csv')
  raw=path.read_bytes() if path.is_file() else urllib.request.urlopen(dataset['url'],timeout=45).read()
  digest=hashlib.sha256(raw).hexdigest()
  if digest!=dataset['sha256']:raise ValueError('Dataset checksum mismatch: '+dataset['id']+'; the benchmark was not run.')
  path.write_bytes(raw)
  reader=csv.DictReader(io.StringIO(raw.decode('utf-8-sig')))
  rows=[{'name':r.get(dataset.get('nameColumn','name'),''),'smiles':r[dataset['smilesColumn']],'observed':r[dataset['observedColumn']]} for r in reader]
  process=subprocess.run(['node',str(ROOT/'tools/benchmark-worker.js')],input=json.dumps({'endpoint':dataset['endpoint'],'rows':rows}),text=True,capture_output=True,check=True,cwd=ROOT)
  report=json.loads(process.stdout);report.pop('rows')
  reports.append({**dataset,'result':report})
 modelFiles=['js/smiles.js','js/mol.js','js/smarts.js','js/stereo.js','js/descriptors.js','js/rules.js','js/pharmacology.js','js/prediction-benchmarks.js']
 hashes={name:hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in modelFiles}
 output={'schemaVersion':1,'generatedAt':datetime.now(timezone.utc).isoformat(),'sourceHashes':hashes,'datasets':reports,'scope':'External experimental-data comparisons without model tuning. The DLS subset excludes the original ESOL fit compounds according to its curator; BBBP overlap with the passive screen development set has not been audited. Not a clinical or prodrug-specific validation.'}
 if write:
  text=json.dumps(output,indent=2,ensure_ascii=False)
  (ROOT/'validation/independent-benchmarks.json').write_text(text+'\n')
  (ROOT/'data/independent-benchmarks.js').write_text('// Generated by tools/run-independent-benchmarks.py; aggregate results only.\nglobalThis.INDEPENDENT_BENCHMARKS = '+text+';\n')
 for row in reports:print(row['id'],json.dumps({'scored':row['result']['scored'],'input':row['result']['inputRows'],'metrics':row['result']['metrics']}))
 return output

if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--cache',type=Path,default=ROOT/'.benchmark-cache');parser.add_argument('--write',action='store_true');args=parser.parse_args();run(args.cache,args.write)
