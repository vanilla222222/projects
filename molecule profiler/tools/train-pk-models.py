#!/usr/bin/env python3
"""Fixed-protocol exploratory models; no test-set hyperparameter optimization.

Inputs are public dataset snapshots with explicit provenance. Splits group full
connectivity/tautomer variants and ring scaffolds before training, calibration or
testing. Calibration residual intervals do not guarantee coverage under scaffold
shift or for an individual patient. No pharmacological effect model is fitted.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import numpy as np
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error,r2_score

ROOT=Path(__file__).resolve().parents[1]
FEATURE_FILES=['js/pk-features.js','tools/pk-features.js','js/smiles.js','js/mol.js','js/stereo.js','js/smarts.js','js/descriptors.js','js/fingerprints.js','tools/train-pk-models.py']


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--half-life',type=Path,required=True);ap.add_argument('--logd',type=Path,required=True)
    ap.add_argument('--rdkit-python',required=True)
    args=ap.parse_args();models={};reports={};parity=[];raw=[]
    for key,path,delimiter,smiles_key,y_key,units,transform,source,transport in [
       ('halfLife',args.half_life,'\t','X','Y','h','log10','https://pubmed.ncbi.nlm.nih.gov/18426954/','https://huggingface.co/datasets/tianle233/icrl-data/resolve/cf2394f455d7c2f9af13e352ccc6efb12fbdfd22/data/half_life_obach.tab'),
       ('logD74',args.logd,',','smiles','exp','log10 distribution coefficient','identity','https://doi.org/10.6019/CHEMBL3301361','https://deepchemdata.s3-us-west-1.amazonaws.com/datasets/Lipophilicity.csv')]:
        rows=list(csv.DictReader(path.read_text().splitlines(),delimiter=delimiter))
        # RDKit only assigns split groups and rejects ambiguous/unsupported input;
        # descriptors/fingerprints are generated by the deployed JavaScript engine.
        rdcode=r'''
import json,sys
from rdkit import Chem,RDLogger
from rdkit.Chem.Scaffolds import MurckoScaffold
from rdkit.Chem.MolStandardize import rdMolStandardize
RDLogger.DisableLog('rdApp.*')
out=[]
for s in json.load(sys.stdin):
 try:
  m=Chem.MolFromSmiles(s)
  if m is None or len(Chem.GetMolFrags(m))!=1 or any(a.GetSymbol() not in {'C','N','O','S','P','F','Cl','Br','I'} or a.GetNumRadicalElectrons() for a in m.GetAtoms()):raise ValueError()
  m=rdMolStandardize.Uncharger().uncharge(m)
  en=rdMolStandardize.TautomerEnumerator();en.SetRemoveSp3Stereo(False);en.SetRemoveBondStereo(False);e=en.Enumerate(m)
  if e.status!=rdMolStandardize.TautomerEnumeratorStatus.Completed:raise ValueError()
  m=en.PickCanonical(e);identity=Chem.MolToSmiles(m,isomericSmiles=True);Chem.RemoveStereochemistry(m)
  scaffold=MurckoScaffold.GetScaffoldForMol(m)
  # Group all acyclic structures together rather than leaking close acyclic
  # analogues across the three splits.
  out.append({'identity':identity,'scaffold':Chem.MolToSmiles(scaffold) or '[ACYCLIC]'})
 except Exception:out.append(None)
print(json.dumps(out))
'''
        groups=json.loads(subprocess.check_output([args.rdkit_python,'-c',rdcode],input=json.dumps([r[smiles_key] for r in rows]),text=True))
        features=json.loads(subprocess.check_output(['node','tools/pk-features.js'],cwd=ROOT,input=json.dumps([r[smiles_key] for r in rows]),text=True))
        valid=[];seen=set();excluded=[]
        for i,(r,g,f) in enumerate(zip(rows,groups,features)):
            try:y=float(r[y_key]);assert np.isfinite(y) and (transform!='log10' or y>0)
            except Exception:excluded.append({'row':i,'reason':'invalid endpoint'});continue
            if g is None or 'error' in f:excluded.append({'row':i,'reason':'unsupported graph/features'});continue
            if g['identity'] in seen:excluded.append({'row':i,'reason':'duplicate standardized stereo identity; first record retained'});continue
            seen.add(g['identity']);valid.append((i,r,g,f,np.log10(y) if transform=='log10' else y))
        # Predeclared deterministic scaffold partition: 60/20/20 by hash bucket.
        split=lambda g:int(hashlib.sha256(('mp-pk-v1:'+g).encode()).hexdigest()[:8],16)%10
        partitions=[[v for v in valid if split(v[2]['scaffold']) in buckets] for buckets in [range(6),range(6,8),range(8,10)]]
        train,cal,test=partitions
        if min(map(len,partitions))<20:raise ValueError('Insufficient scaffold partition')
        X=lambda part:np.array([v[3]['values'] for v in part]);Y=lambda part:np.array([v[4] for v in part])
        model=RandomForestRegressor(n_estimators=96,max_depth=8,min_samples_leaf=4,max_features=.65,random_state=20261020,n_jobs=2)
        model.fit(X(train),Y(train));cp=model.predict(X(cal));tp=model.predict(X(test));baseline=np.full(len(test),np.median(Y(train)))
        residuals=np.sort(abs(Y(cal)-cp));rank=min(len(cal),int(np.ceil((len(cal)+1)*.90)));radius=float(residuals[rank-1])
        metrics={'testN':len(test),'mae':float(mean_absolute_error(Y(test),tp)),'medianBaselineMae':float(mean_absolute_error(Y(test),baseline)),
                 'r2':float(r2_score(Y(test),tp)),'observedIntervalCoverage':float(np.mean(abs(Y(test)-tp)<=radius)),
                 'metricScale':'log10 hours' if transform=='log10' else 'logD at pH 7.4'}
        enabled=metrics['mae']<metrics['medianBaselineMae']*.95
        trees=[]
        for tree in model.estimators_:
            t=tree.tree_;trees.append([[-1,float(t.value[i,0,0])] if t.children_left[i]==-1 else [int(t.feature[i]),float(t.threshold[i]),int(t.children_left[i]),int(t.children_right[i])] for i in range(t.node_count)])
        models[key]={'version':'pk-exploratory-v1','enabled':enabled,'units':units,'sourceUrl':source,'transportUrl':transport,'inputSha256':hashlib.sha256(path.read_bytes()).hexdigest(),'transform':transform,'trees':trees,'residualRadius':radius,
                     'bounds':[[float(np.min(X(train)[:,i])),float(np.max(X(train)[:,i]))] for i in range(12)],
                     'trainingBits':[''.join(map(str,v[3]['bits'])) for v in train],'metrics':metrics}
        report={'sourceUrl':source,'transportUrl':transport,'inputSha256':hashlib.sha256(path.read_bytes()).hexdigest(),'inputRows':len(rows),'included':len(valid),
                'excluded':excluded,'partitions':{name:[{'row':v[0],'scaffold':v[2]['scaffold'],'identity':v[2]['identity']} for v in part] for name,part in zip(['train','calibration','test'],partitions)},
                'metrics':metrics,'enabled':enabled,'calibrationResidualRadius':radius,
                'caveats':['Exploratory internal scaffold holdout; not external experimental validation.','Half-life transport is a third-party TDC-format mirror; official Harvard download returned HTTP 403. Mirror equivalence was not independently confirmed.' if key=='halfLife' else 'Lipophilicity_AstraZeneca endpoint is logD at pH 7.4, not intrinsic logP.',
                           'Scaffold shift can invalidate nominal 90% interval coverage.','No patient covariates, dose, formulation, active-metabolite kinetics or individual clinical predictions.','Coarse 256-bit stereo-aware fingerprint can collide; predictions are not identity matches.']}
        reports[key]=report
        for v,p in zip(test[:12],tp[:12]):parity.append({'model':key,'smiles':v[1][smiles_key],'features':v[3]['values'],'predictionTransformed':float(p)})
        raw.append({'model':key,'sourceUrl':source,'transportUrl':transport,'rows':rows})
        print(key,json.dumps(metrics),'enabled',enabled,flush=True)
    hashes={p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in FEATURE_FILES}
    payload={'schemaVersion':1,'sourceSha256':hashes,'models':models}
    text="'use strict';\n// Exploratory measured-endpoint regressions; see PK-PREDICTIONS.md.\nconst PK_MODELS = "+json.dumps(payload,separators=(',',':'))+";\nif(typeof module!=='undefined'&&module.exports)module.exports={PK_MODELS};\n"
    (ROOT/'data/pk-models.js').write_text(text)
    (ROOT/'validation/pk-model-evaluation.json').write_text(json.dumps({'schemaVersion':1,'sourceSha256':hashes,'modelSha256':hashlib.sha256(text.encode()).hexdigest(),'protocol':'Fixed 60/20/20 hash-based non-overlapping achiral scaffold groups; stereo-preserving neutral tautomer identity deduplication; training only on train; residual radius from calibration only; no refit or tuning on test. Enable only if test MAE beats training-median baseline by at least 5%.','models':reports,'parity':parity},indent=2)+'\n')
    (ROOT/'validation/pk-training-sources.json').write_text(json.dumps(raw,separators=(',',':'))+'\n')


if __name__=='__main__':main()
