# Scores our Wildman-Crippen log P and molar refractivity against RDKit's.
# Both implement the same published atom-contribution table, so this is an
# exactness check on the implementation, not a prediction accuracy: the right
# answer is agreement to within rounding. The SMILES come from whichever
# dataset CSV is passed, which keeps the check on real, varied chemistry.
# Usage: python3 -I tools/crippen-conformance.py <csv> <smiles-column> [--write]
import csv, json, os, subprocess, sys
from rdkit import Chem, RDLogger
from rdkit.Chem import Crippen
RDLogger.DisableLog('rdApp.*')

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
path = sys.argv[1]
column = sys.argv[2]

smiles = []
with open(path, newline='') as handle:
    for row in csv.DictReader(handle):
        value = (row.get(column) or '').strip()
        if value:
            smiles.append(value)

listing = os.path.join(root, 'tools', '.crippen-input.smi')
with open(listing, 'w') as handle:
    handle.write('\n'.join(smiles) + '\n')
proc = subprocess.run(['node', os.path.join(root, 'tools/property-validation.js'),
                       '--dump', listing], capture_output=True, text=True)
os.remove(listing)
if proc.returncode != 0:
    print(proc.stderr[-3000:])
    sys.exit(1)

logp_diff = []
mr_diff = []
mismatch = []
skipped = 0
for line in proc.stdout.strip().split('\n'):
    smi, mine_logp, _, mine_mr = line.split('\t')
    mol = Chem.MolFromSmiles(smi)
    if mol is None or mine_logp == 'NA':
        skipped += 1
        continue
    theirs_logp = Crippen.MolLogP(mol)
    theirs_mr = Crippen.MolMR(mol)
    dp = float(mine_logp) - theirs_logp
    dm = float(mine_mr) - theirs_mr
    logp_diff.append(abs(dp))
    mr_diff.append(abs(dm))
    if abs(dp) > 0.05:
        mismatch.append((smi, float(mine_logp), round(theirs_logp, 4), round(dp, 4)))

n = len(logp_diff)
stat = {
    'generated': __import__('datetime').date.today().isoformat(),
    'source': os.path.basename(path),
    'compounds': n,
    'skipped': skipped,
    'logPMeanAbsDiff': round(sum(logp_diff) / n, 4),
    'logPMaxAbsDiff': round(max(logp_diff), 4),
    'logPWithin0_05': round(sum(1 for d in logp_diff if d <= 0.05) * 100.0 / n, 2),
    'logPWithin0_5': round(sum(1 for d in logp_diff if d <= 0.5) * 100.0 / n, 2),
    'mrMeanAbsDiff': round(sum(mr_diff) / n, 4),
    'mrMaxAbsDiff': round(max(mr_diff), 4),
    'mrWithin0_5': round(sum(1 for d in mr_diff if d <= 0.5) * 100.0 / n, 2),
    'disagreeOver0_05': len(mismatch),
    'disagreements': [{'smiles': row[0], 'ours': row[1], 'rdkit': row[2], 'diff': row[3]}
                      for row in mismatch[:20]]
}
print(json.dumps(stat, indent=2))
for row in mismatch[:15]:
    print('  ', row)

if '--write' in sys.argv:
    out = os.path.join(root, 'data/crippencases.js')
    with open(out, 'w') as handle:
        handle.write('// Generated by tools/crippen-conformance.py. Do not edit by hand.\n'
                     '// Our Wildman-Crippen log P and molar refractivity against RDKit\'s.\n'
                     'const CRIPPEN_CONFORMANCE = ' + json.dumps(stat, indent=2) + ';\n\n'
                     'if (typeof module !== \'undefined\' && module.exports) {\n'
                     '  module.exports = { CRIPPEN_CONFORMANCE };\n}\n')
    print('wrote data/crippencases.js')
