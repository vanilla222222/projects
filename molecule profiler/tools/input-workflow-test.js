'use strict';
const assert=require('node:assert/strict');
const {parseInputText,csvColumns,summarizeOutcomes,safeCell,createSnapshot,parseSnapshot}=require('../js/input-workflow.js');
assert.deepEqual(csvColumns('"A, quoted","C, C"',','),['A, quoted','C, C']);
assert.deepEqual(csvColumns('"A ""name""",CCO',','),['A "name"','CCO']);
assert.throws(()=>csvColumns('"broken',','),/Unterminated/);
const csv=parseInputText('name,smiles\n"Example, one",CCO\nbad,\n');
assert.equal(csv.format,'csv');
assert.equal(csv.rows[0].name,'Example, one');
assert.equal(csv.rows[0].smiles,'CCO');
assert.match(csv.rows[1].error,/empty/);
assert.equal(csv.rows[1].line,3);
const tsv=parseInputText('SMILES\tNAME\r\nO\tWater\r\n');
assert.equal(tsv.format,'tsv');
assert.equal(tsv.rows[0].smiles,'O');
assert.equal(tsv.rows[0].name,'Water');
const plain=parseInputText(' CC \n \nO');
assert.equal(plain.format,'plain');
assert.deepEqual(plain.rows.map(x=>x.line),[1,3]);
assert.equal(parseInputText('').rows.length,0);
assert.equal(summarizeOutcomes(2,[{line:1}],3).status,'2 analyzed · 1 skipped');
assert.ok(safeCell('=SUM(1,2)').startsWith('"\'='));
assert.equal(safeCell('-1.2'),'"-1.2"');
const snap=createSnapshot([{name:'Water',smiles:'O',d:{formula:'H2O',mw:18,exactMass:18,tpsa:0,hbd:1,hba:1,rotatableBonds:0,rings:0,charge:0,logp:-1,mr:3},v:{logS:0.5}}],{generatedAt:'2026-10-19T00:00:00Z'});
assert.equal(snap.molecules[0].estimates.aqueousLogS,0.5);
assert.equal(snap.molecules[0].descriptors.molecularWeight,18);
assert.match(snap.declaration,/not laboratory measurements/);
const reopened=parseSnapshot(JSON.stringify(snap));
assert.equal(reopened.format,'snapshot');
assert.equal(reopened.rows[0].name,'Water');
assert.equal(reopened.rows[0].smiles,'O');
assert.equal(reopened.rows[0].descriptors,undefined);
assert.equal(reopened.source.generatedAt,'2026-10-19T00:00:00Z');
assert.equal(parseInputText('  '+JSON.stringify(snap)).format,'snapshot');
assert.equal(parseSnapshot('\uFEFF'+JSON.stringify(snap)).rows.length,1);
assert.throws(()=>parseSnapshot('{broken'),/Invalid JSON/);
assert.throws(()=>parseSnapshot('[]'),/not a Molecule Profiler/);
assert.throws(()=>parseSnapshot(JSON.stringify({...snap,tool:'Other'})),/not a Molecule Profiler/);
assert.throws(()=>parseSnapshot(JSON.stringify({...snap,schemaVersion:2})),/Unsupported/);
assert.throws(()=>parseSnapshot(JSON.stringify({...snap,molecules:{}})),/array/);
assert.match(parseInputText('{broken').error,/Invalid JSON/);
const mixed=parseSnapshot(JSON.stringify({...snap,molecules:[
  null,[],{smiles:''},{smiles:42},{smiles:'O',name:12},
  {smiles:' CCO ',name:'<img src=x onerror=alert(1)>',descriptors:{molecularWeight:99999}}
]}));
assert.equal(mixed.rows.filter(row=>row.error).length,5);
assert.equal(mixed.rows[5].smiles,'CCO');
assert.equal(mixed.rows[5].name,'<img src=x onerror=alert(1)>');
assert.equal(mixed.rows[5].location,'Snapshot molecule 6');
assert.equal(mixed.rows[5].descriptors,undefined);
assert.equal(parseInputText('[NH4+]').format,'plain', 'bracket SMILES must not be interpreted as a JSON array');
const multiline=parseInputText('name,smiles,notes\r\n"First, ""quoted""\nsecond line",CCO,"note\ncontinued"\r\nBroken, ,missing\r\nWater,O,ok');
assert.equal(multiline.rows.length,3);
assert.equal(multiline.rows[0].line,2);
assert.equal(multiline.rows[0].name,'First, "quoted"\nsecond line');
assert.equal(multiline.rows[1].line,5);
assert.match(multiline.rows[1].error,/empty/);
assert.equal(multiline.rows[2].line,6);
const structureOnly=parseInputText('smiles\nO\nCCO');
assert.equal(structureOnly.format,'csv');
assert.equal(structureOnly.rows.length,2);
assert.equal(structureOnly.rows[0].name,'');
const packageInput=parseInputText('\uFEFF"molecule_id","name","input_smiles","formula"\r\n"mol-0001","Water","O","H2O"');
assert.equal(packageInput.rows[0].smiles,'O');
assert.equal(packageInput.rows[0].name,'Water');
assert.equal(parseInputText('molecule_name,smiles\nWater,O').rows[0].name,'Water');
assert.match(parseInputText('name,smiles,input_smiles\nWater,O,CCO').error,/Ambiguous/);
assert.match(parseInputText('name,smiles\n"Unclosed\nname,CCO').rows[0].error,/Unterminated/);
assert.equal(parseInputText('name,smiles,"extra\tcolumn"\nWater,O,x').format,'csv');
console.log('Input workflow: snapshots, package CSV, multiline records, structure-only headers and line numbers passed');
