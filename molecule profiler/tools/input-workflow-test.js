'use strict';
const assert=require('node:assert/strict');
const {parseInputText,csvColumns,summarizeOutcomes,safeCell,createSnapshot}=require('../js/input-workflow.js');
assert.deepEqual(csvColumns('"A, quoted","C, C"',','),['A, quoted','C, C']);
assert.deepEqual(csvColumns('"A ""name""",CCO',','),['A "name"','CCO']);
assert.throws(()=>csvColumns('"broken',','),/Unterminated/);
const csv=parseInputText('name,smiles\n"Example, one",CCO\nbad,\n');
assert.equal(csv.format,'csv');
assert.equal(csv.rows[0].name,'Example, one');
assert.equal(csv.rows[0].smiles,'CCO');
assert.match(csv.rows[1].error,/empty/);
assert.equal(csv.rows[1].line,3);
const tsv=parseInputText('SMILES\tNAME\r\nO\tWater\r\n');
assert.equal(tsv.format,'tsv');
assert.equal(tsv.rows[0].smiles,'O');
assert.equal(tsv.rows[0].name,'Water');
const plain=parseInputText(' CC \n \nO');
assert.equal(plain.format,'plain');
assert.deepEqual(plain.rows.map(x=>x.line),[1,3]);
assert.equal(parseInputText('').rows.length,0);
assert.equal(summarizeOutcomes(2,[{line:1}],3).status,'2 analyzed · 1 skipped');
assert.ok(safeCell('=SUM(1,2)').startsWith('"\'='));
assert.equal(safeCell('-1.2'),'"-1.2"');
const snap=createSnapshot([{name:'Water',smiles:'O',d:{formula:'H2O',mw:18,exactMass:18,tpsa:0,hbd:1,hba:1,rotatableBonds:0,rings:0,charge:0,logp:-1,mr:3},v:{logS:0.5}}],{generatedAt:'2026-10-19T00:00:00Z'});
assert.equal(snap.molecules[0].estimates.aqueousLogS,0.5);
assert.equal(snap.molecules[0].descriptors.molecularWeight,18);
assert.match(snap.declaration,/not laboratory measurements/);
console.log('Input workflow tests passed');
