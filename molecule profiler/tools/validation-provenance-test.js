'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const {capture,compare} = require('./validation-provenance.js');
const root = fs.mkdtempSync(path.join(os.tmpdir(),'mp-provenance-'));
try {
  fs.mkdirSync(path.join(root,'js'));
  fs.mkdirSync(path.join(root,'tools'));
  fs.writeFileSync(path.join(root,'index.html'),'<html></html>');
  fs.writeFileSync(path.join(root,'js','app.js'),'// μ\n');
  const initial = capture(root);
  assert.equal(initial.fileCount,2);
  assert.equal(initial.git.available,false);
  assert.equal(initial.git.sourceDirty,null, 'missing Git must not be labelled a clean checkout');
  assert.equal(initial.files.find(file=>file.path==='js/app.js').bytes,Buffer.byteLength('// μ\n'));
  fs.writeFileSync(path.join(root,'validation-report.json'),'{}');
  fs.writeFileSync(path.join(root,'tools','run.log'),'ignored output');
  assert.equal(capture(root).digest,initial.digest, 'generated reports must not change source identity');
  fs.writeFileSync(path.join(root,'js','app.js'),'// changed\n');
  let result=compare(initial,capture(root));
  assert.equal(result.stable,false);
  assert.deepEqual(result.changedFiles,['js/app.js']);
  fs.unlinkSync(path.join(root,'js','app.js'));
  fs.writeFileSync(path.join(root,'js','new.js'),'// new\n');
  result=compare(initial,capture(root));
  assert.deepEqual(result.changedFiles,['js/app.js','js/new.js']);
  const init=spawnSync('git',['init','--quiet'],{cwd:root});
  assert.equal(init.status,0);
  spawnSync('git',['add','.'],{cwd:root});
  const commit=spawnSync('git',['-c','user.name=Test','-c','user.email=test@example.invalid','commit','--quiet','-m','Fixture'],{cwd:root});
  assert.equal(commit.status,0);
  const clean=capture(root);
  assert.match(clean.git.commit,/^[a-f0-9]{40,64}$/);
  assert.equal(clean.git.sourceDirty,false);
  fs.writeFileSync(path.join(root,'index.html'),'changed');
  assert.equal(capture(root).git.sourceDirty,true);
  assert.ok(capture(root).git.changes.some(change=>change.path==='index.html' && change.status===' M'));
  assert.equal(compare(clean,{...clean,git:{...clean.git,commit:'another'}}).stable,false);
  console.log('Validation provenance: deterministic SHA-256, changed/added/deleted files, Git revision and dirty state passed');
} finally {fs.rmSync(root,{recursive:true,force:true});}
