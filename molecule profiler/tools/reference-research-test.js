'use strict';
const assert=require('node:assert/strict');
global.CURATED_REFERENCES=require('../data/curated-references').CURATED_REFERENCES;
global.CuratedReferences=require('../js/curated-references');
global.LIBRARY_NAME_METADATA=require('../data/library-names').LIBRARY_NAME_METADATA;
global.LIBRARY_TAG_METADATA=require('../data/library-tags').LIBRARY_TAG_METADATA;
global.LIBRARY_RECEPTOR_METADATA=require('../data/library-receptor-tags').LIBRARY_RECEPTOR_METADATA;
const catalog=require('../js/library-catalog'),curated=global.CuratedReferences,data=global.CURATED_REFERENCES;
const entries=curated.library(require('../data/library').LIBRARY),api=require('../js/reference-research');
const model=api.createModel({entries,catalog,curated,data});
const control=data.records.find(r=>r.id==='control-gsk-j2'),less=control.compounds[1].libraryNames[0],active=control.compounds[0].libraryNames[0];
assert.equal(model.dossier(less).observations.find(o=>o.recordId==='control-gsk-j2').value,100);
assert.equal(model.dossier(less).observations.find(o=>o.recordId==='control-gsk-j2').relation,'>');
assert.equal(model.dossier(active).observations.find(o=>o.recordId==='control-gsk-j2').value,0.06);
const two=model.dossier('2C-B').observations.find(o=>o.kind==='functional_assay');assert.equal(two.species,'Homo sapiens');assert.equal(two.hostSpecies,'Mus musculus');assert.equal(two.value,80);assert.equal(two.efficacy.value,45);
assert.equal(model.dossier('Valsartan').identityWarnings.length,1);assert.ok(!model.dossier('Valsartan').records.some(r=>r.id==='family-003-3937-agtr1'));
assert.equal(model.dossier('missing'),null);
const original=entries.find(e=>e.name===less),mutated={...original,smiles:'C'};assert.ok(!model.observations(mutated).some(o=>o.recordId==='control-gsk-j2'),'Do not transfer evidence on a name-only match');
console.log('Research dossiers: graph guards, participant-specific censored control values, receptor/host species and identity warnings passed');
module.exports={model,api,data,entries};
