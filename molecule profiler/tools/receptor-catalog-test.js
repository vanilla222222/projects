'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {RECEPTOR_REFERENCE_CATALOG:catalog}=require('../data/receptor-catalog.js');
const {RECEPTOR_LIGAND_ANNOTATIONS:annotations}=require('../data/receptor-ligand-annotations.js');
const api=require('../js/receptor-catalog.js');
const {TARGETS}=require('../data/targets.js');
const {LIBRARY}=require('../data/library.js');
const rows=catalog.receptors;
assert.ok(rows.length>=140,'Expanded receptor inventory missing');
assert.equal(new Set(rows.map(r=>r.id)).size,rows.length,'Duplicate stable IDs');
const required=['id','name','family','kind','mechanism','endogenousLigands','description','activation','blockade','caution','species','evidenceType'];
for(const r of rows) {
  for(const key of required)assert.ok(typeof r[key]==='string'&&r[key].trim(),r.id+' missing '+key);
  assert.equal(r.species,'Homo sapiens');
  assert.ok(r.genes.length>0);
  assert.ok(r.sources.length>=r.genes.length);
  for(const gene of r.genes)assert.ok(r.sources.some(s=>s.label==='NCBI Gene: '+gene),'Missing gene source '+gene);
  for(const s of r.sources){assert.equal(new URL(s.url).protocol,'https:');assert.ok(s.scope);}
  assert.deepEqual(r.ligandAnnotations,[], 'Receptor summaries must not fabricate ligand actions');
}
const existing=TARGETS.filter(t=>t.family==='GPCR'||t.family==='Nuclear receptor'||/receptor/i.test(t.name)
  || ['EGFR','ERBB2','KDR','PDGFRB','KIT','ALK','MET','FLT3'].includes(t.gene));
for(const t of existing)assert.ok(rows.some(r=>api.links(r,[t]).length), 'Existing receptor missing biology coverage: '+t.gene);
const get=id=>rows.find(r=>r.id===id);
for(const id of ['DRD5','HTR1E','HTR1F','HTR4','HTR5A','HRH3','HRH4','CHRM4','CHRM5','MTNR1B','CNR1','CNR2','OPRL1','GRM8','P2RX7','HCRTR2','TACR3','CXCR4'])assert.ok(get(id),id+' missing');
assert.equal(rows.some(r=>r.id==='HTR5BP'||r.id==='HTR5B'),false,'Human pseudogene must not be represented as a functional receptor');
assert.ok(get('GABAB').genes.includes('GABBR1')&&get('GABAB').genes.includes('GABBR2'));
assert.match(get('GABAB').caution,/both/);
assert.equal(api.links(get('GABAA'),TARGETS)[0].mapping,'legacy_subunit');
assert.match(get('ERBB2').endogenousLigands,/No established direct/);
assert.match(get('P2RX6').activation,/assembly/);
assert.match(get('NMDA').caution,/co-agonist/i);
assert.deepEqual(api.validateAnnotations(annotations,rows,LIBRARY),[]);
const fixture={receptorId:'DRD1',ligandName:'Dopamine',action:'agonist',sourceUrl:'https://example.org/functional-record',evidenceType:'functional',species:'Homo sapiens',assay:'cell-based cAMP',endpoint:'cAMP response'};
assert.deepEqual(api.validateAnnotations([fixture],rows,LIBRARY),[]);
assert.ok(api.validateAnnotations([{...fixture,evidenceType:'binding'}],rows,LIBRARY).some(e=>/functional evidence/.test(e.message)));
assert.ok(api.validateAnnotations([{...fixture,action:'pam'}],rows,LIBRARY).some(e=>/probe ligand/.test(e.message)));
assert.ok(api.validateAnnotations([{...fixture,action:'biased'}],rows,LIBRARY).some(e=>/compared pathways/.test(e.message)));
assert.ok(api.validateAnnotations([{...fixture,sourceUrl:'javascript:alert(1)'}],rows,LIBRARY).length);
assert.ok(api.validateAnnotations([{...fixture,assay:{}}],rows,LIBRARY).length);
assert.ok(api.validateAnnotations([{...fixture,ligandName:'dopamine'}],rows,LIBRARY).length);
assert.ok(api.validateAnnotations([{...fixture,receptorId:'made-up'}],rows,LIBRARY).length);
assert.equal(api.browse(rows,{search:'5-HT1F'},TARGETS,annotations)[0].id,'HTR1F');
assert.ok(api.browse(rows,{search:'cholin'},TARGETS,annotations).some(r=>r.id==='CHRM1'));
assert.ok(api.browse(rows,{family:'Dopamine'},TARGETS,annotations).length===5);
assert.equal(api.browse(rows,{coverage:'annotated'},TARGETS,[]).length,0);
const awaiting=api.browse(rows,{coverage:'awaiting'},TARGETS,annotations);
assert.ok(awaiting.length>=90);
assert.ok(awaiting.some(r=>r.id==='DRD5'));
const untouched=JSON.stringify(TARGETS);
const handoff=api.createHandoff(rows,TARGETS);
assert.equal(handoff.receptors.length,rows.length);
assert.deepEqual(handoff.ligandAnnotations,[]);
assert.ok(handoff.receptors.every(r=>r.targetTemplate.ligands.length===0));
assert.equal(JSON.stringify(TARGETS),untouched,'Scaffold export must not mutate target ranking data');
const html=fs.readFileSync(path.join(__dirname,'../reference-explorer.html'),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'Duplicate explorer DOM IDs');
for(const id of ['receptor-browser','molecule-browser','receptor-detail','receptor-search','receptor-family','receptor-kind','receptor-coverage','action-glossary','receptor-export'])assert.ok(ids.includes(id),id+' missing');
for(const file of ['data/receptor-catalog.js','data/receptor-ligand-annotations.js','js/receptor-catalog.js','js/receptor-explorer-ui.js'])assert.ok(html.includes(file),file+' not loaded');
const linked=rows.filter(r=>api.links(r,TARGETS).length).length;
console.log(`Receptor catalog: ${rows.length} records, ${new Set(rows.map(r=>r.family)).size} families, ${linked} existing target links, ${awaiting.length} awaiting target rows; identity, action-evidence and scaffold contracts passed`);
