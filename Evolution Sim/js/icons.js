function circ(x, y, r) {
	return `M${x - r} ${y}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`;
}

const EYE = (x, y, r = 1) => ['#141414', circ(x, y, r)];
const BARK = '#6b4a2e';
const STEM = '#4a7d36';

function petals(cx, cy, d, r) {
	let out = '';
	for (let k = 0; k < 5; k++) {
		const a = -Math.PI / 2 + (k * Math.PI * 2) / 5;
		out += circ(cx + Math.cos(a) * d, cy + Math.sin(a) * d, r);
	}
	return out;
}

function ell(x, y, rx, ry) {
	return `M${x - rx} ${y}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0z`;
}

function ellR(x, y, rx, ry, deg) {
	const a = (deg * Math.PI) / 180;
	const f = (v) => +v.toFixed(2);
	const dx = rx * Math.cos(a);
	const dy = rx * Math.sin(a);
	return `M${f(x - dx)} ${f(y - dy)}a${rx} ${ry} ${deg} 1 0 ${f(2 * dx)} ${f(2 * dy)}a${rx} ${ry} ${deg} 1 0 ${f(-2 * dx)} ${f(-2 * dy)}z`;
}

function spokes(cx, cy, r1, r2, n, a0 = 0, span = 360) {
	const f = (v) => +v.toFixed(2);
	let out = '';
	const full = span >= 360;
	for (let k = 0; k < n; k++) {
		const a = ((a0 + (k * span) / (full ? n : Math.max(1, n - 1))) * Math.PI) / 180;
		out += `M${f(cx + Math.cos(a) * r1)} ${f(cy + Math.sin(a) * r1)}L${f(cx + Math.cos(a) * r2)} ${f(cy + Math.sin(a) * r2)}`;
	}
	return out;
}

function starPath(cx, cy, ro, ri, n, sy = 1, a0 = -90) {
	const f = (v) => +v.toFixed(2);
	let out = '';
	for (let k = 0; k < n * 2; k++) {
		const r = k % 2 ? ri : ro;
		const a = ((a0 + (k * 180) / n) * Math.PI) / 180;
		out += (k ? 'L' : 'M') + f(cx + Math.cos(a) * r) + ' ' + f(cy + Math.sin(a) * r * sy);
	}
	return out + 'z';
}

function ringOf(cx, cy, d, r, n, a0 = -90) {
	let out = '';
	for (let k = 0; k < n; k++) {
		const a = ((a0 + (k * 360) / n) * Math.PI) / 180;
		out += circ(+(cx + Math.cos(a) * d).toFixed(2), +(cy + Math.sin(a) * d).toFixed(2), r);
	}
	return out;
}

