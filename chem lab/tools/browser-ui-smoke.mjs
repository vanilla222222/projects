// Optional real-browser suite. Install Playwright, then run this file.
// CHEM_PLAYWRIGHT_PATH and CHEM_CHROMIUM_EXECUTABLE support external runtimes.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.CHEM_PLAYWRIGHT_PATH || 'playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.resolve(process.env.CHEM_BROWSER_OUTPUT || '/tmp/chem-lab-browser-qa');
fs.mkdirSync(output, { recursive: true });
const types = { '.js': 'application/javascript', '.css': 'text/css', '.html': 'text/html', '.woff2': 'font/woff2', '.png': 'image/png' };
const server = http.createServer((req, res) => {
  try {
    let file = path.resolve(root, '.' + decodeURIComponent(new URL(req.url, 'http://local').pathname));
    if (file !== root && !file.startsWith(root + path.sep)) throw Error('Invalid path');
    if (fs.statSync(file).isDirectory()) file = path.join(file, 'index.html');
    res.setHeader('Content-Type', types[path.extname(file)] || 'application/octet-stream');
    res.end(fs.readFileSync(file));
  } catch { res.statusCode = 404; res.end('Not found'); }
});
await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
const origin = 'http://127.0.0.1:' + server.address().port;
const launch = { headless: true };
if (process.env.CHEM_CHROMIUM_EXECUTABLE) launch.executablePath = process.env.CHEM_CHROMIUM_EXECUTABLE;
if (process.env.CHEM_CHROMIUM_ARGS) launch.args = JSON.parse(process.env.CHEM_CHROMIUM_ARGS);
let browser;
let browserVersion = '';
const checks = [], screenshots = [];
const checked = (name, value) => { assert.ok(value, name); checks.push(name); };
try {
  for (const profile of [{ name: 'desktop', width: 1440, height: 1000 }, { name: 'mobile', width: 390, height: 844 }]) {
    browser = await chromium.launch(launch);
    browserVersion = browser.version();
    const context = await browser.newContext({ viewport: { width: profile.width, height: profile.height }, isMobile: profile.name === 'mobile', hasTouch: profile.name === 'mobile', acceptDownloads: true });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(origin, { waitUntil: 'networkidle' });
    checked(profile.name + ': editor startup', await page.getByRole('tab', { name: 'Editor', exact: true }).getAttribute('aria-selected') === 'true');
    await page.getByRole('tab', { name: 'Path Finder', exact: true }).click();
    await page.locator('#path-start').fill('C=C');
    await page.locator('#path-target').fill('CC(=O)O');
    await page.locator('#path-run').click();
    await page.waitForFunction(() => !document.getElementById('path-run').disabled, null, { timeout: 25000 });
    checked(profile.name + ': routes found', /routes? found/.test(await page.locator('#path-status').innerText()));
    checked(profile.name + ': alternatives shown', await page.locator('.route-comparison-card').count() >= 2);
    checked(profile.name + ': assumptions shown', (await page.locator('.route-comparison').innerText()).toLowerCase().includes('assumption'));
    const flow = await page.locator('.route-comparison-grid').evaluate((el) => getComputedStyle(el).gridAutoFlow);
    checked(profile.name + ': responsive route layout', profile.name === 'mobile' ? flow === 'row' : flow === 'column');
    const pageWidth = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, viewport: innerWidth }));
    checked(profile.name + ': no page horizontal overflow', pageWidth.scroll <= pageWidth.viewport + 1);
    const compareScreenshot = path.join(output, profile.name + '-comparison.png');
    await page.screenshot({ path: compareScreenshot, fullPage: true }); screenshots.push(compareScreenshot);
    await page.getByRole('button', { name: /^Save route 1 to workspace$/ }).click();
    checked(profile.name + ': workspace handoff', await page.locator('body').getAttribute('data-view') === 'workspace');
    checked(profile.name + ': saved route verified', (await page.locator('#route-workspace').innerText()).includes('Route status: verified'));
    const routeName = profile.name + ' browser regression route';
    await page.getByLabel('Route name', { exact: true }).fill(routeName);
    await page.getByLabel('Route name', { exact: true }).press('Tab');
    await page.reload({ waitUntil: 'networkidle' });
    checked(profile.name + ': persisted route after reload', await page.getByLabel('Route name', { exact: true }).inputValue() === routeName);
    const firstStep = page.locator('.workspace-step').first();
    await firstStep.getByText('Edit inputs and conditions', { exact: true }).click();
    await firstStep.getByLabel('Notes', { exact: true }).fill('Browser condition edit check');
    await firstStep.getByRole('button', { name: 'Apply edits and recheck', exact: true }).click();
    checked(profile.name + ': edited conditions revalidated', (await page.locator('#route-workspace').innerText()).includes('Route status: verified'));
    await page.getByRole('button', { name: 'Move down', exact: true }).first().click();
    checked(profile.name + ': reordered route invalidated', (await page.locator('#route-workspace').innerText()).includes('Route status: invalid'));
    await page.getByRole('button', { name: 'Move up', exact: true }).nth(1).click();
    checked(profile.name + ': route continuity restored', (await page.locator('#route-workspace').innerText()).includes('Route status: verified'));
    const [jsonDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export JSON', exact: true }).click()]);
    const jsonFile = path.join(output, profile.name + '-route.json'); await jsonDownload.saveAs(jsonFile);
    const route = JSON.parse(fs.readFileSync(jsonFile, 'utf8'));
    checked(profile.name + ': JSON export', route.name === routeName && route.steps.length >= 2);
    checked(profile.name + ': condition edit survives export', route.steps[0].conditions.notes === 'Browser condition edit check');
    const [csvDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export CSV', exact: true }).click()]);
    const csvFile = path.join(output, profile.name + '-route.csv'); await csvDownload.saveAs(csvFile);
    const csv = fs.readFileSync(csvFile, 'utf8');
    checked(profile.name + ': readable CSV export', csv.includes('Verification,Explanation') && !csv.includes('NaN'));
    await page.locator('#route-workspace input[type=file]').setInputFiles(jsonFile);
    await page.getByText('Imported 1 route(s). Verification was recomputed.', { exact: true }).waitFor();
    checked(profile.name + ': JSON reimport', await page.getByLabel('Saved route', { exact: true }).locator('option').count() === 2);
    const workspaceScreenshot = path.join(output, profile.name + '-workspace.png');
    await page.screenshot({ path: workspaceScreenshot, fullPage: true }); screenshots.push(workspaceScreenshot);
    await page.getByRole('button', { name: 'Open in Reactions', exact: true }).first().click();
    checked(profile.name + ': step opens in Reactions', await page.locator('body').getAttribute('data-view') === 'reactions');
    checked(profile.name + ': evidence rendered', await page.locator('#reaction-view .rx-evidence').count() > 0);
    await page.locator('#rx-rule-explorer > summary').click();
    const search = page.locator('#rx-rule-explorer input');
    await search.fill('hydrogenation');
    checked(profile.name + ': rule explorer search', (await page.locator('#rx-rule-explorer .rx-rule-results').innerText()).toLowerCase().includes('hydrogenation'));
    await page.getByRole('tab', { name: 'Editor', exact: true }).click();
    checked(profile.name + ': return to editor', await page.locator('body').getAttribute('data-view') === 'editor');
    await page.getByRole('tab', { name: 'Path Finder', exact: true }).click();
    await page.locator('#path-depth').selectOption('10');
    checked(profile.name + ': ten-step setting', await page.locator('#path-depth').inputValue() === '10');
    checked(profile.name + ': extended search budget disclosed', (await page.locator('#path-search-limits').innerText()).includes('30'));
    await page.locator('#path-depth').selectOption('3');
    await page.locator('#path-route-count').selectOption('1');
    await page.locator('#path-start').fill('NCCO');
    await page.locator('#path-target').fill('NCCOC(C)=O');
    await page.locator('.path-options > summary').click();
    await page.locator('#path-stock-policy').selectOption('custom');
    await page.locator('#path-inventory').fill('CC(=O)Cl');
    await page.locator('#path-forbidden-rules').fill('fischer');
    await page.locator('#path-run').click();
    await page.waitForFunction(() => !document.getElementById('path-run').disabled, null, { timeout: 30000 });
    checked(profile.name + ': explicit protection route found', /routes? found/.test(await page.locator('#path-status').innerText()));
    checked(profile.name + ': protection counted as three steps', await page.locator('.route-comparison-step').count() === 3);
    const planText = await page.locator('.route-comparison').textContent();
    checked(profile.name + ': protection rationale present', planText.includes('Protection plan: protect') && planText.includes('Protection plan: deprotect'));
    await page.getByRole('button', { name: /^Save route 1 to workspace$/ }).click();
    checked(profile.name + ': saved protection route verified', (await page.locator('#route-workspace').innerText()).includes('Route status: verified'));
    const [planDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export JSON', exact: true }).click()]);
    const planFile = path.join(output, profile.name + '-protected-route.json'); await planDownload.saveAs(planFile);
    const plan = JSON.parse(fs.readFileSync(planFile, 'utf8'));
    checked(profile.name + ': protection survives JSON export', plan.steps.length === 3 && plan.steps[0].planning.kind === 'protect' && plan.steps[2].planning.kind === 'deprotect');
    checked(profile.name + ': no runtime errors', errors.length === 0);
    await context.close();
    await browser.close();
    browser = null;
  }
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  const sourceHashes = Object.fromEntries([...html.matchAll(/(?:<script src|<link rel="stylesheet" href)="([^"]+)"/g)].map((match) => [match[1], createHash('sha256').update(fs.readFileSync(path.join(root, match[1]))).digest('hex')]));
  sourceHashes['index.html'] = createHash('sha256').update(html).digest('hex');
  const report = { status: 'passed', browser: browserVersion, profiles: ['1440×1000 desktop', '390×844 mobile/touch emulation'], checks: checks.length, results: checks, sourceHashes, screenshots: screenshots.map((file) => path.basename(file)), limitation: 'Mobile/touch viewport emulation, not physical Android or iOS device testing.' };
  fs.writeFileSync(path.join(output, 'browser-ui-report.json'), JSON.stringify(report, null, 2) + '\n');
  console.log('Browser UI: ' + checks.length + ' checks passed on desktop and mobile. Report: ' + path.join(output, 'browser-ui-report.json'));
} finally {
  if (browser) await browser.close();
  server.close();
}
