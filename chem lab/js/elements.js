const PERIODIC_BY_SYMBOL = new Map(PERIODIC_ELEMENTS.map((element) => [element.symbol, element]));

const METAL_CATEGORIES = new Set(['alkali', 'alkaline', 'transition', 'post-transition', 'lanthanide', 'actinide']);

function periodicElement(symbol) {
  return PERIODIC_BY_SYMBOL.get(symbol === 'D' ? 'H' : symbol) || null;
}

function isMetalElement(symbol) {
  const element = PERIODIC_BY_SYMBOL.get(symbol);
  return !!element && METAL_CATEGORIES.has(element.category);
}

function fillElementTable(table, pick) {
  PERIODIC_ELEMENTS.forEach((element) => {
    if (!Object.prototype.hasOwnProperty.call(table, element.symbol)) {
      const value = pick(element);
      if (value !== undefined) {
        table[element.symbol] = value;
      }
    }
  });
  return table;
}
