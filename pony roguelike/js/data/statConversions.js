function statConvBonus(player){
  const sp = player.statPassives || {}, r = {};
  for (const id in sp) { const c = STAT_CONVERTED_ITEMS[id]; if (c) r[c] = (r[c] || 0) + sp[id]; }
  return new Proxy(r, { get: (o, k) => o[k] || 0 });
}
